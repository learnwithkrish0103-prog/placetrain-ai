// Helper to safely find or provide fallback question
function getQuestion(id: string, fallbackTopic: string) {
  const found = VERIFIED_QUESTION_BANK.find((q) => q.id === id);
  if (found) return found;
  const topicMatch = VERIFIED_QUESTION_BANK.find((q) => q.topic.toLowerCase().includes(fallbackTopic.toLowerCase()));
  if (topicMatch) return topicMatch;
  return VERIFIED_QUESTION_BANK[0];
}

